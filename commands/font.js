const UPSIDEDOWN_MAP = {
    a: 'ɐ', b: 'q', c: 'ɔ', d: 'p', e: 'ǝ', f: 'ɟ', g: 'ƃ', h: 'ɥ', i: 'ᴉ',
    j: 'ɾ', k: 'ʞ', l: 'l', m: 'ɯ', n: 'u', o: 'o', p: 'd', q: 'b', r: 'ɹ',
    s: 's', t: 'ʇ', u: 'n', v: 'ʌ', w: 'ʍ', x: 'x', y: 'ʎ', z: 'z',
    '.': '˙', ',': "'", "'": ',', '?': '¿', '!': '¡'
};

function convert(text, style) {
    if (style === 'upsidedown') {
        return text
            .toLowerCase()
            .split('')
            .reverse()
            .map(ch => UPSIDEDOWN_MAP[ch] ?? ch)
            .join('');
    }
    const table = STYLES[style];
    if (!table) return null;
    return text
        .split('')
        .map(ch => {
            const idx = NORMAL.indexOf(ch);
            return idx === -1 ? ch : [...table][idx] || ch;
        })
        .join('');
}

const STYLE_LIST = [...Object.keys(STYLES), 'upsidedown'];

async function fontCommand(sock, chatId, message, args) {
    const style = (args[0] || '').toLowerCase();
    const text = args.slice(1).join(' ');

    if (!style || !STYLE_LIST.includes(style) || !text) {
        await sock.sendMessage(chatId, {
            text: `🔤 *Générateur de police stylée*\n\nUsage : .font <style> <texte>\n\nStyles disponibles :\n${STYLE_LIST.map(s => `• ${s}`).join('\n')}\n\nExemple : .font bold Salut tout le monde`
        }, { quoted: message });
        return;
    }

    const result = convert(text, style);
    await sock.sendMessage(chatId, { text: result }, { quoted: message });
}

module.exports = fontCommand;
